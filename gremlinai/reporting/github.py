"""
GremlinAI — GitHub issue export.

POST /api/bugs/{id}/github creates a GitHub issue.
If GITHUB_TOKEN is not set, raises GitHubNotConfigured (UI shows disabled button).
"""
from __future__ import annotations
import logging

import httpx

from gremlinai.models import BugReport

logger = logging.getLogger(__name__)


class GitHubNotConfigured(Exception):
    pass


async def create_issue(bug: BugReport, token: str, repo: str) -> str:
    """
    Create a GitHub issue for a bug report.
    Returns the issue URL.
    Raises GitHubNotConfigured if token/repo are empty.
    """
    if not token or not repo:
        raise GitHubNotConfigured(
            "GITHUB_TOKEN and GITHUB_REPO must be set to export issues."
        )

    repro_md = "\n".join(f"{i+1}. {step}" for i, step in enumerate(bug.repro_steps))
    console_md = "\n".join(f"- {e}" for e in bug.console_errors) or "_None_"
    body = (
        f"## Bug Report: {bug.title}\n\n"
        f"**Severity:** {bug.severity}  \n"
        f"**Step:** {bug.step_id}  \n"
        f"**Criterion:** {bug.criterion_id or 'N/A'}  \n\n"
        f"### Expected\n{bug.expected}\n\n"
        f"### Actual\n{bug.actual}\n\n"
        f"### Repro Steps\n{repro_md}\n\n"
        f"### Console Errors\n{console_md}\n\n"
        f"> Generated by GremlinAI — Run `{bug.run_id}`"
    )

    payload = {
        "title": f"[GremlinAI] {bug.title}",
        "body": body,
        "labels": ["gremlinai", "bug", bug.severity],
    }

    async with httpx.AsyncClient(timeout=15.0) as client:
        resp = await client.post(
            f"https://api.github.com/repos/{repo}/issues",
            json=payload,
            headers={
                "Authorization": f"Bearer {token}",
                "Accept": "application/vnd.github+json",
                "X-GitHub-Api-Version": "2022-11-28",
            },
        )
        resp.raise_for_status()
        issue_url: str = resp.json()["html_url"]
        logger.info("GitHub issue created: %s", issue_url)
        return issue_url
